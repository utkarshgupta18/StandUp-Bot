"""Thin database helper layer for SQLite (default) or Postgres. No ORM.

Set DATABASE_URL=postgresql://... to use Postgres; otherwise a SQLite file
under DATA_DIR is used. SQL here is written once with `?` placeholders and
portable syntax (INSERT ... RETURNING, ON CONFLICT), and translated for
Postgres at execution time.
"""
from __future__ import annotations

import json
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

from app.config import DATABASE_URL, SQLITE_PATH

_SCHEMA_PATH = Path(__file__).resolve().parent / "schema.sql"

IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))

_DIALECT = {
    "sqlite": {
        "pk": "INTEGER PRIMARY KEY AUTOINCREMENT",
        "now": "(datetime('now'))",
    },
    "postgres": {
        "pk": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "now": "(to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'))",
    },
}

# Columns added after a table first shipped. CREATE TABLE IF NOT EXISTS won't
# add them to a database created by an older version, so init_db adds them.
_ADDED_COLUMNS = {
    "updates": {"status_json": "TEXT"},
    "ingestion_runs": {"items_ingested": "INTEGER NOT NULL DEFAULT 0"},
    "documents": {"source_id": "INTEGER"},
}

Row = dict[str, Any]


def now() -> str:
    """Current UTC time in the format every timestamp column uses."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


class _Conn:
    """Minimal common interface over a sqlite3 or psycopg connection."""

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql: str, params: tuple | list = ()):
        if IS_POSTGRES:
            sql = sql.replace("?", "%s")
        return self.raw.execute(sql, params)

    def insert(self, sql: str, params: tuple | list = ()) -> int:
        """Run an INSERT ... RETURNING id and return the new id."""
        return self.execute(sql + " RETURNING id", params).fetchone()["id"]


@contextmanager
def get_conn():
    if IS_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row

        raw = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    else:
        raw = sqlite3.connect(SQLITE_PATH)
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA foreign_keys = ON")
    try:
        yield _Conn(raw)
        raw.commit()
    finally:
        raw.close()


def _one(row) -> Optional[Row]:
    return dict(row) if row is not None else None


def _all(rows) -> list[Row]:
    return [dict(r) for r in rows]


# ------------------------------------------------------------------ schema
def _schema_sql() -> str:
    dialect = _DIALECT["postgres" if IS_POSTGRES else "sqlite"]
    return _SCHEMA_PATH.read_text().replace("{pk}", dialect["pk"]).replace("{now}", dialect["now"])


def _migrate_sqlite_documents_check(conn: _Conn) -> None:
    """Databases from before Phase 4 restrict documents.source_type to doc/commit.

    SQLite can't drop a CHECK constraint, so rebuild the table without it.
    """
    row = conn.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name='documents'").fetchone()
    if not row or "CHECK" not in row["sql"]:
        return
    conn.raw.commit()
    conn.execute("PRAGMA foreign_keys = OFF")
    conn.raw.executescript(
        """
        BEGIN;
        ALTER TABLE documents RENAME TO documents_old;
        CREATE TABLE documents (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            project_id      INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
            source_type     TEXT NOT NULL,
            source_ref      TEXT NOT NULL,
            content_hash    TEXT NOT NULL,
            chunk_ids       TEXT,
            last_ingested_at TEXT NOT NULL DEFAULT (datetime('now')),
            UNIQUE(project_id, source_type, source_ref)
        );
        INSERT INTO documents SELECT * FROM documents_old;
        DROP TABLE documents_old;
        CREATE INDEX IF NOT EXISTS idx_documents_project ON documents(project_id);
        COMMIT;
        """
    )
    conn.execute("PRAGMA foreign_keys = ON")


def init_db() -> None:
    with get_conn() as conn:
        if IS_POSTGRES:
            conn.raw.execute(_schema_sql())
            for table, columns in _ADDED_COLUMNS.items():
                for column, col_type in columns.items():
                    conn.raw.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {col_type}")
        else:
            _migrate_sqlite_documents_check(conn)
            conn.raw.executescript(_schema_sql())
            for table, columns in _ADDED_COLUMNS.items():
                existing = {row["name"] for row in conn.execute(f"PRAGMA table_info({table})")}
                for column, col_type in columns.items():
                    if column not in existing:
                        conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {col_type}")


# ---------------------------------------------------------------- projects
def create_project(name: str, docs_path: Optional[str] = None, repo_path: Optional[str] = None) -> int:
    with get_conn() as conn:
        return conn.insert(
            "INSERT INTO projects (name, docs_path, repo_path, created_at) VALUES (?, ?, ?, ?)",
            (name, docs_path, repo_path, now()),
        )


def get_project_by_name(name: str) -> Optional[Row]:
    with get_conn() as conn:
        return _one(conn.execute("SELECT * FROM projects WHERE name = ?", (name,)).fetchone())


def get_project(project_id: int) -> Optional[Row]:
    with get_conn() as conn:
        return _one(conn.execute("SELECT * FROM projects WHERE id = ?", (project_id,)).fetchone())


def list_projects(project_ids: Optional[list[int]] = None) -> list[Row]:
    """All projects, or only those in project_ids (used for per-user access)."""
    with get_conn() as conn:
        rows = _all(conn.execute("SELECT * FROM projects ORDER BY name").fetchall())
    if project_ids is not None:
        allowed = set(project_ids)
        rows = [r for r in rows if r["id"] in allowed]
    return rows


def upsert_project_paths(project_id: int, docs_path: Optional[str] = None, repo_path: Optional[str] = None) -> None:
    with get_conn() as conn:
        if docs_path is not None:
            conn.execute("UPDATE projects SET docs_path = ? WHERE id = ?", (docs_path, project_id))
        if repo_path is not None:
            conn.execute("UPDATE projects SET repo_path = ? WHERE id = ?", (repo_path, project_id))


def delete_project(project_id: int) -> None:
    """Delete a project; documents, sources, runs, updates and access rows cascade."""
    with get_conn() as conn:
        conn.execute("DELETE FROM projects WHERE id = ?", (project_id,))


# --------------------------------------------------------------- documents
def get_document(project_id: int, source_type: str, source_ref: str) -> Optional[Row]:
    with get_conn() as conn:
        return _one(conn.execute(
            "SELECT * FROM documents WHERE project_id = ? AND source_type = ? AND source_ref = ?",
            (project_id, source_type, source_ref),
        ).fetchone())


def upsert_document(
    project_id: int,
    source_type: str,
    source_ref: str,
    content_hash: str,
    chunk_ids: list[str],
    source_id: Optional[int] = None,
) -> None:
    ts = now()
    with get_conn() as conn:
        conn.execute(
            """
            INSERT INTO documents (project_id, source_type, source_ref, content_hash, chunk_ids, last_ingested_at, source_id)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(project_id, source_type, source_ref)
            DO UPDATE SET content_hash=excluded.content_hash,
                          chunk_ids=excluded.chunk_ids,
                          last_ingested_at=excluded.last_ingested_at,
                          source_id=excluded.source_id
            """,
            (project_id, source_type, source_ref, content_hash, ",".join(chunk_ids), ts, source_id),
        )


def delete_document(project_id: int, source_type: str, source_ref: str) -> None:
    with get_conn() as conn:
        conn.execute(
            "DELETE FROM documents WHERE project_id = ? AND source_type = ? AND source_ref = ?",
            (project_id, source_type, source_ref),
        )


def list_documents(project_id: int, source_type: Optional[str] = None) -> list[Row]:
    with get_conn() as conn:
        if source_type:
            return _all(conn.execute(
                "SELECT * FROM documents WHERE project_id = ? AND source_type = ?",
                (project_id, source_type),
            ).fetchall())
        return _all(conn.execute("SELECT * FROM documents WHERE project_id = ?", (project_id,)).fetchall())


def list_source_documents(source_id: int) -> list[Row]:
    with get_conn() as conn:
        return _all(conn.execute("SELECT * FROM documents WHERE source_id = ?", (source_id,)).fetchall())


def document_counts(project_id: int) -> dict:
    """Ingested units per source type; doc and commit are always present."""
    with get_conn() as conn:
        rows = conn.execute(
            "SELECT source_type, COUNT(*) AS n FROM documents WHERE project_id = ? GROUP BY source_type",
            (project_id,),
        ).fetchall()
    counts = {"doc": 0, "commit": 0}
    counts.update({row["source_type"]: row["n"] for row in rows})
    return counts


# ----------------------------------------------------------------- sources
def create_source(project_id: int, kind: str, name: str, config: dict) -> int:
    with get_conn() as conn:
        return conn.insert(
            "INSERT INTO sources (project_id, kind, name, config, created_at) VALUES (?, ?, ?, ?, ?)",
            (project_id, kind, name, json.dumps(config), now()),
        )


def _source_dict(row) -> Optional[Row]:
    data = _one(row)
    if data is not None:
        data["config"] = json.loads(data["config"] or "{}")
    return data


def get_source(source_id: int) -> Optional[Row]:
    with get_conn() as conn:
        return _source_dict(conn.execute("SELECT * FROM sources WHERE id = ?", (source_id,)).fetchone())


def list_sources(project_id: int) -> list[Row]:
    with get_conn() as conn:
        rows = conn.execute("SELECT * FROM sources WHERE project_id = ? ORDER BY id", (project_id,)).fetchall()
    return [_source_dict(r) for r in rows]


def mark_source_synced(source_id: int, error: Optional[str] = None) -> None:
    with get_conn() as conn:
        if error is None:
            conn.execute("UPDATE sources SET last_synced_at = ?, last_error = NULL WHERE id = ?", (now(), source_id))
        else:
            conn.execute("UPDATE sources SET last_error = ? WHERE id = ?", (error, source_id))


def delete_source(source_id: int) -> None:
    with get_conn() as conn:
        conn.execute("DELETE FROM sources WHERE id = ?", (source_id,))


# ---------------------------------------------------------- ingestion runs
def start_ingestion_run(project_id: int, trigger: str = "manual") -> int:
    with get_conn() as conn:
        return conn.insert(
            "INSERT INTO ingestion_runs (project_id, trigger, started_at) VALUES (?, ?, ?)",
            (project_id, trigger, now()),
        )


def finish_ingestion_run(
    run_id: int,
    status: str,
    docs_ingested: int = 0,
    docs_removed: int = 0,
    commits_ingested: int = 0,
    items_ingested: int = 0,
    errors: Optional[list[str]] = None,
) -> None:
    with get_conn() as conn:
        conn.execute(
            """
            UPDATE ingestion_runs
            SET finished_at = ?, status = ?, docs_ingested = ?, docs_removed = ?,
                commits_ingested = ?, items_ingested = ?, errors = ?
            WHERE id = ?
            """,
            (now(), status, docs_ingested, docs_removed, commits_ingested, items_ingested,
             "\n".join(errors or []) or None, run_id),
        )


def list_ingestion_runs(project_id: int, limit: int = 20) -> list[Row]:
    with get_conn() as conn:
        return _all(conn.execute(
            "SELECT * FROM ingestion_runs WHERE project_id = ? ORDER BY id DESC LIMIT ?",
            (project_id, limit),
        ).fetchall())


def latest_ingestion_run(project_id: int) -> Optional[Row]:
    runs = list_ingestion_runs(project_id, limit=1)
    return runs[0] if runs else None


# ----------------------------------------------------------------- updates
def add_update(project_id: int, summary: str, source_refs: list[str], status: Optional[dict] = None) -> int:
    with get_conn() as conn:
        return conn.insert(
            "INSERT INTO updates (project_id, summary, source_refs, status_json, generated_at) VALUES (?, ?, ?, ?, ?)",
            (project_id, summary, ",".join(source_refs), json.dumps(status) if status is not None else None, now()),
        )


def get_update(update_id: int) -> Optional[Row]:
    with get_conn() as conn:
        return _one(conn.execute("SELECT * FROM updates WHERE id = ?", (update_id,)).fetchone())


def latest_update(project_id: int) -> Optional[Row]:
    with get_conn() as conn:
        return _one(conn.execute(
            "SELECT * FROM updates WHERE project_id = ? ORDER BY generated_at DESC, id DESC LIMIT 1",
            (project_id,),
        ).fetchone())


def update_to_dict(row: Optional[Row]) -> Optional[dict]:
    """Decode an `updates` row into a plain dict with the structured status parsed."""
    if row is None:
        return None
    data = dict(row)
    data["source_refs"] = [r for r in (data.get("source_refs") or "").split(",") if r]
    raw = data.pop("status_json", None)
    try:
        data["status"] = json.loads(raw) if raw else None
    except json.JSONDecodeError:
        data["status"] = None
    return data


