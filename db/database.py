def set_user_projects(user_id: int, project_ids: list[int]) -> None:
    with get_conn() as conn:
        conn.execute("DELETE FROM project_access WHERE user_id = ?", (user_id,))
        for pid in sorted(set(project_ids)):
            conn.execute("INSERT INTO project_access (user_id, project_id) VALUES (?, ?)", (user_id, pid))


def user_project_ids(user_id: int) -> list[int]:
    with get_conn() as conn:
        rows = conn.execute("SELECT project_id FROM project_access WHERE user_id = ? ORDER BY project_id", (user_id,)).fetchall()
    return [r["project_id"] for r in rows]
